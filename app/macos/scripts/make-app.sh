# Assembles HyperBuf.app (for development). Bundles the Web core (core/dist) into Contents/Resources/web.
# Signing is ad-hoc (for running locally). Developer ID signing, notarization and packaging:
# scripts/release.sh (docs/dev/release.md).
# Usage: app/macos/scripts/make-app.sh [debug|release]   (default: release)  → app/macos/.build/HyperBuf.app
set -euo pipefail
cd "$(dirname "$0")/../../.."   # repository root

config="${1:-release}"
(cd core && npm ci --silent && npm run build >/dev/null)
# Replace the absolute source path of the build machine (a personal path) so it does not remain in the
# executable
root="$(pwd -P)"
remap=()
archs=()
if [ "$config" = "release" ]; then
  remap=(-Xswiftc -file-prefix-map -Xswiftc "$root=/hyperbuf")
  # The distributed build is Universal (both Apple Silicon and Intel), so it also runs on Intel Macs (e.g. a
  # 2018 Mac mini)
  archs=(--arch arm64 --arch x86_64)
fi
# A debug build finds core/dist from the source path (#filePath) (WebRoot.swift), so the path is not replaced.
# Only the dev machine's architecture is built
build() { # $1=directory → builds and prints the output directory
  (cd "$1" && swift build -c "$config" ${archs[@]+"${archs[@]}"} ${remap[@]+"${remap[@]}"} >/dev/null \
    && swift build -c "$config" ${archs[@]+"${archs[@]}"} --show-bin-path)
}
app_bin="$(build app/macos)"
cli_bin="$(build cli)"

app="app/macos/.build/HyperBuf.app"
rm -rf "$app"
mkdir -p "$app/Contents/MacOS" "$app/Contents/Resources"
cp "$app_bin/HyperBuf" "$app/Contents/MacOS/HyperBuf"
cp -R core/dist "$app/Contents/Resources/web"
# The CLI (hyperbuf) is bundled too. It goes in Resources/bin, not Contents/MacOS, so it does not clash with
# the app's executable (HyperBuf)
# on a case-insensitive file system. Put it on PATH via a Homebrew cask binary or a symlink
mkdir -p "$app/Contents/Resources/bin"
cp "$cli_bin/hyperbuf" "$app/Contents/Resources/bin/hyperbuf"
# Copyright notices and licenses (distribution terms) of the bundled third-party software. Placed outside the
# Web serving scope (web/)
# Icon (generated by app/macos/scripts/make-icon.swift and checked into the repository)
# Setting the environment variable HYPERBUF_ICON to the path of an .icns swaps in a different icon (for
# comparison)
icon="${HYPERBUF_ICON:-app/macos/Resources/AppIcon.icns}"
[ -f "$icon" ] || { echo "Icon not found: $icon" >&2; exit 1; }
cp "$icon" "$app/Contents/Resources/AppIcon.icns"
cp LICENSE "$app/Contents/Resources/LICENSE.txt"
cp NOTICE "$app/Contents/Resources/NOTICE.txt"
(cd core && node scripts/licenses.mjs notices "../$app/Contents/Resources/THIRD-PARTY-NOTICES.txt" >/dev/null)

# The Bundle ID is the reverse of an owned domain (yhojo.com) (docs/history/migration-plan.md §8).
cat > "$app/Contents/Info.plist" <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleExecutable</key><string>HyperBuf</string>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>CFBundleIdentifier</key><string>com.yhojo.hyperbuf</string>
  <key>CFBundleName</key><string>HyperBuf</string>
  <key>CFBundleDisplayName</key><string>HyperBuf</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>0.0.0</string>
  <key>CFBundleVersion</key><string>0</string>
  <key>NSHumanReadableCopyright</key><string>Copyright 2026 Yasuo Hojo. Apache License 2.0.</string>
  <key>LSMinimumSystemVersion</key><string>14.0</string>
  <key>LSApplicationCategoryType</key><string>public.app-category.productivity</string>
  <key>NSHighResolutionCapable</key><true/>
  <key>NSPrincipalClass</key><string>NSApplication</string>
  <!-- hyperbuf:// : launching the app and "open" from external links (docs/dev/integration-protocol.md §5.2) -->
  <key>CFBundleURLTypes</key>
  <array>
    <dict>
      <key>CFBundleURLName</key><string>com.yhojo.hyperbuf.url</string>
      <key>CFBundleURLSchemes</key><array><string>hyperbuf</string></array>
    </dict>
  </array>
  <!-- Finder's "Open With" and drag & drop onto the Dock (Markdown and folders).
       It does not become the default app (Alternate). docs/dev/buffer-model.md §5.1 -->
  <key>CFBundleDocumentTypes</key>
  <array>
    <dict>
      <key>CFBundleTypeName</key><string>Markdown</string>
      <key>CFBundleTypeRole</key><string>Viewer</string>
      <key>LSHandlerRank</key><string>Alternate</string>
      <key>LSItemContentTypes</key>
      <array><string>net.daringfireball.markdown</string></array>
      <key>CFBundleTypeExtensions</key><array><string>md</string><string>markdown</string></array>
    </dict>
    <dict>
      <key>CFBundleTypeName</key><string>Folder</string>
      <key>CFBundleTypeRole</key><string>Viewer</string>
      <key>LSHandlerRank</key><string>Alternate</string>
      <key>LSItemContentTypes</key>
      <array><string>public.folder</string></array>
    </dict>
  </array>
</dict>
</plist>
PLIST
# The version is authoritative in Version.swift (updated at release). The build number is the commit count
version="$(sed -n 's/^public let hyperBufVersion = "\(.*\)"$/\1/p' app/macos/Sources/HyperBufKit/Version.swift)"
build="$(git rev-list --count HEAD 2>/dev/null || echo 0)"
/usr/libexec/PlistBuddy -c "Set :CFBundleShortVersionString $version" -c "Set :CFBundleVersion $build" "$app/Contents/Info.plist"
codesign --force --sign - "$app/Contents/Resources/bin/hyperbuf" >/dev/null 2>&1
codesign --force --sign - "$app" >/dev/null 2>&1
echo "$app"
