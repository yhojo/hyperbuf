// Generates docs/user/syntax-highlighting.md from the grammar list (src/grammars.ts).
// Usage: node scripts/gen-languages.ts          generate and write
//         node scripts/gen-languages.ts --check  check that it is up to date (exit code 1 if not)

import { readFileSync, writeFileSync } from "node:fs";
import type { Grammar } from "@wooorm/starry-night";
import { EAGER, LAZY } from "../src/grammars.ts";

const target = new URL("../../docs/user/syntax-highlighting.md", import.meta.url);

const lazyGrammars = await Promise.all(LAZY.map((g) => g.load()));
const lazyScopes = new Set(lazyGrammars.map((g) => g.scopeName));

const row = (g: Grammar, mode: string): string => {
  const names = g.names.map((n) => `\`${n}\``).join(", ");
  const exts = g.extensions.length > 0 ? g.extensions.map((e) => `\`${e}\``).join(" ") : "";
  return `| ${names} | ${exts} | ${mode} |`;
};

const rows = [
  ...EAGER.map((g) => ({ g, mode: "Always" })),
  ...lazyGrammars.map((g) => ({ g, mode: "On demand" })),
]
  .filter(({ g }) => g.names.length > 0)
  .filter(({ g }, i, all) => all.findIndex((x) => x.g.scopeName === g.scopeName) === i)
  .sort((a, b) => (a.g.names[0] as string).localeCompare(b.g.names[0] as string))
  .map(({ g, mode }) => row(g, lazyScopes.has(g.scopeName) ? "On demand" : mode));

const generated = `<!-- Generated by core/scripts/gen-languages.ts. Do not edit by hand (after changing core/src/grammars.ts, regenerate with \`npm run languages\`) -->

# Syntax highlighting

A code block whose language is given (\` \`\`\`elisp \`) is colored with the same grammars as GitHub (starry-night). ${rows.length} languages are supported.
You can use any of the names in "Names you can use" below (case-insensitive) or a file extension (\` \`\`\`.el \`).
If no language is given, or it is not in the list, the block is not colored (the document is shown as it is).
\`mermaid\` is not colored but rendered as a diagram.

"Grammar loading" says when the grammar is loaded. The grammars marked "On demand" are large, so they are loaded only when you open a document that has a code block in that language (the first open may take slightly longer).

| Names you can use | Extensions | Grammar loading |
| --- | --- | --- |
${rows.join("\n")}
`;

if (process.argv.includes("--check")) {
  const current = (() => {
    try {
      return readFileSync(target, "utf8");
    } catch {
      return "";
    }
  })();
  if (current !== generated) {
    console.error(
      "docs/user/syntax-highlighting.md is out of date with the code. Regenerate it with: node scripts/gen-languages.ts",
    );
    process.exit(1);
  }
} else {
  writeFileSync(target, generated);
}
